/**
 * Feature landing pages: the content source of truth for the `[slug]` dynamic
 * route (`/practice/<slug>` for Chinese, `/en/practice/<slug>` for English).
 *
 * Each entry is one self-contained, indexable landing page. The page keeps its
 * own metadata (title / description / Open Graph) and body copy so a single
 * template can render every page via `generateStaticParams` + `generateMetadata`.
 *
 * How to add a page (or later a blog post under the same pattern):
 *   1. Add an entry to `landingPages` below with a unique `slug`.
 *   2. Keep `lastModified` in sync with the "last updated" line the template
 *      renders and with the entry added to `app/sitemap.ts`.
 *   3. Generate its social card with `node scripts/generate-og-images.mjs`
 *      and point `ogImage` at `/og-<slug>.png`.
 *
 * Field meanings:
 *   - slug:          URL segment; also the key used by generateStaticParams.
 *   - lastModified:  ISO-8601 date of the last content edit. Used by sitemap
 *                    and rendered as the page's "last updated" line.
 *   - ogImage:       Public path to the 1200x630 social card (generated by
 *                    scripts/generate-og-images.mjs).
 *   - locales.zh/en: Per-language metadata and body copy.
 *       - metaTitle/Description: <title> and meta description for the page.
 *         The root layout appends "｜DuolinTing 多邻听" via the title template.
 *       - ogTitle/Description:   Open Graph / Twitter card copy.
 *       - ogAlt:                 Alt text for the social card image.
 *       - hero:                  H1 area (eyebrow kicker, title, lead).
 *       - sections:              Body sections (eyebrow, H2, paragraph, bullets).
 *       - faq:                   FAQPage items; also rendered on-page.
 */

