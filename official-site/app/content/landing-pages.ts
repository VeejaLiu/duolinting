/** Look up a single landing page by its URL slug. Returns undefined for unknown slugs. */
export function getLandingPage(slug: string): LandingPage | undefined {
  return landingPages.find((page) => page.slug === slug);
}

/**
 * Localized public path for a landing page: `/practice/<slug>` for Chinese,
 * `/en/practice/<slug>` for English. Used by generateMetadata (canonical /
 * hreflang) and internal links.
 */
export function landingPagePath(slug: string, locale: Locale): string {
  const base = `/practice/${slug}`;
  return locale === "en" ? `/en${base}` : base;
}
